import AppKit
import Carbon.HIToolbox
import SwiftUI

struct ClipItem: Codable, Identifiable, Hashable {
    var id = UUID()
    var text: String
    var date: Date
}

/// Remembers the last 15 pieces of text copied anywhere on the Mac.
@MainActor
final class ClipboardHistory: ObservableObject {
    static let shared = ClipboardHistory()
    static let limit = 15

    @Published private(set) var items: [ClipItem] = []
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?

    private var file: URL {
        FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask)[0]
            .appendingPathComponent("Glint", isDirectory: true).appendingPathComponent("clipboard-history.json")
    }

    var enabled: Bool { Prefs.d.object(forKey: "clipboardHistory") as? Bool ?? true }

    func start() {
        if let d = try? Data(contentsOf: file), let saved = try? JSONDecoder().decode([ClipItem].self, from: d) { items = saved }
        timer = Timer.scheduledTimer(withTimeInterval: 0.4, repeats: true) { _ in
            Task { @MainActor in ClipboardHistory.shared.poll() }
        }
    }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard enabled else { return }
        // Respect password managers and apps that mark data as private or temporary.
        let skip: Set<String> = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
        if let types = pb.types?.map(\.rawValue), types.contains(where: skip.contains) { return }
        guard let s = pb.string(forType: .string), !s.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        record(s)
    }

    private func record(_ s: String) {
        items.removeAll { $0.text == s }
        items.insert(ClipItem(text: s, date: Date()), at: 0)
        if items.count > Self.limit { items.removeLast(items.count - Self.limit) }
        save()
    }

    /// Puts an item back on the clipboard (it moves to the top of the history).
    func copy(_ item: ClipItem) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(item.text, forType: .string)
        lastChange = pb.changeCount
        record(item.text)
    }

    func remove(_ item: ClipItem) {
        items.removeAll { $0.id == item.id }
        save()
    }

    func clear() {
        items = []
        save()
    }

    private func save() {
        try? FileManager.default.createDirectory(at: file.deletingLastPathComponent(), withIntermediateDirectories: true)
        if let d = try? JSONEncoder().encode(items) { try? d.write(to: file, options: .atomic) }
    }
}

extension ClipItem {
    var preview: String {
        text.trimmingCharacters(in: .whitespacesAndNewlines)
            .replacingOccurrences(of: "\n", with: " ⏎ ")
            .replacingOccurrences(of: "\t", with: " ")
    }
    var ago: String {
        let f = RelativeDateTimeFormatter()
        f.unitsStyle = .abbreviated
        return f.localizedString(for: date, relativeTo: Date())
    }
}

// MARK: - Quick picker (⌃⌘V)

/// Floating list near the pointer. It becomes key without activating Glint, so the app you
/// were typing in stays frontmost and the chosen item is pasted straight into it.
@MainActor
enum ClipboardPicker {
    private static var panel: PickerPanel?
    private static var monitor: Any?
    private static var resignObserver: NSObjectProtocol?
    static let model = PickerModel()

    static func toggle() { panel == nil ? show() : close() }

    static func show() {
        let items = ClipboardHistory.shared.items
        guard !items.isEmpty else {
            Toast.show("Clipboard history is empty — copy some text first", symbol: "doc.on.clipboard")
            return
        }
        model.selected = 0
        let size = CGSize(width: 400, height: min(CGFloat(items.count) * 46 + 64, 560))
        let p = PickerPanel(contentRect: CGRect(origin: .zero, size: size), styleMask: [.borderless, .nonactivatingPanel], backing: .buffered, defer: false)
        p.identifier = GlintChrome.id
        p.isOpaque = false
        p.backgroundColor = .clear
        p.hasShadow = true
        p.level = .popUpMenu
        p.isReleasedWhenClosed = false
        p.collectionBehavior = [.canJoinAllSpaces, .fullScreenAuxiliary]
        let host = NSHostingView(rootView: PickerView(history: ClipboardHistory.shared, model: model))
        host.frame = CGRect(origin: .zero, size: size)
        p.contentView = host
        let m = NSEvent.mouseLocation
        let vf = NSScreen.withMouse.visibleFrame
        let x = min(max(m.x - 30, vf.minX + 8), vf.maxX - size.width - 8)
        let y = min(max(m.y - size.height - 12, vf.minY + 8), vf.maxY - size.height - 8)
        p.setFrame(CGRect(x: x, y: y, width: size.width, height: size.height), display: false)
        p.makeKeyAndOrderFront(nil)
        panel = p
        monitor = NSEvent.addLocalMonitorForEvents(matching: [.keyDown, .leftMouseDown]) { e in
            if e.type == .leftMouseDown { if e.window !== panel { close() }; return e }
            return handle(e) ? nil : e
        }
        resignObserver = NotificationCenter.default.addObserver(forName: NSWindow.didResignKeyNotification, object: p, queue: .main) { _ in
            Task { @MainActor in close() }
        }
    }

    private static func handle(_ e: NSEvent) -> Bool {
        let items = ClipboardHistory.shared.items
        switch Int(e.keyCode) {
        case kVK_Escape: close(); return true
        case kVK_DownArrow: model.selected = min(model.selected + 1, items.count - 1); return true
        case kVK_UpArrow: model.selected = max(model.selected - 1, 0); return true
        case kVK_Return, kVK_ANSI_KeypadEnter:
            if items.indices.contains(model.selected) { choose(items[model.selected], paste: !e.modifierFlags.contains(.command)) }
            return true
        default:
            if let c = e.charactersIgnoringModifiers, let n = Int(c), n >= 0, n <= 9 {
                let i = n == 0 ? 9 : n - 1
                if items.indices.contains(i) { choose(items[i], paste: !e.modifierFlags.contains(.command)) }
                return true
            }
            return false
        }
    }

    /// Copies the item; with `paste`, also sends ⌘V to the app underneath.
    static func choose(_ item: ClipItem, paste: Bool) {
        ClipboardHistory.shared.copy(item)
        close()
        guard paste else { Toast.show("Copied — ready to paste", symbol: "doc.on.clipboard.fill"); return }
        guard AXIsProcessTrusted() else {
            Toast.show("Copied — press ⌘V to paste (allow Accessibility to auto-paste)", symbol: "doc.on.clipboard.fill", duration: 2.6)
            return
        }
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.12) {
            let src = CGEventSource(stateID: .combinedSessionState)
            let down = CGEvent(keyboardEventSource: src, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: true)
            let up = CGEvent(keyboardEventSource: src, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: false)
            down?.flags = .maskCommand
            up?.flags = .maskCommand
            down?.post(tap: .cghidEventTap)
            up?.post(tap: .cghidEventTap)
        }
    }

    static func close() {
        if let m = monitor { NSEvent.removeMonitor(m) }
        monitor = nil
        if let o = resignObserver { NotificationCenter.default.removeObserver(o) }
        resignObserver = nil
        panel?.orderOut(nil)
        panel = nil
    }
}

final class PickerPanel: NSPanel {
    override var canBecomeKey: Bool { true }
}

final class PickerModel: ObservableObject {
    @Published var selected = 0
}

struct PickerView: View {
    @ObservedObject var history: ClipboardHistory
    @ObservedObject var model: PickerModel

    var body: some View {
        VStack(alignment: .leading, spacing: 0) {
            HStack {
                Image(systemName: "doc.on.clipboard.fill").foregroundStyle(Color(hex: 0xA78BFA))
                Text("Clipboard").font(.system(size: 13, weight: .semibold, design: .rounded))
                Spacer()
                Text("1–9 or ⏎ paste · ⌘⏎ copy · esc")
                    .font(.system(size: 10.5))
                    .foregroundStyle(.white.opacity(0.5))
            }
            .padding(.horizontal, 14)
            .frame(height: 40)
            Divider().overlay(Color.white.opacity(0.08))
            ScrollViewReader { proxy in
                ScrollView {
                    VStack(spacing: 2) {
                        ForEach(Array(history.items.enumerated()), id: \.element.id) { i, item in
                            PickerRow(index: i, item: item, selected: model.selected == i)
                                .id(i)
                                .onHover { if $0 { model.selected = i } }
                                .onTapGesture { ClipboardPicker.choose(item, paste: true) }
                        }
                    }
                    .padding(6)
                }
                .onChange(of: model.selected) { _, i in withAnimation(.easeOut(duration: 0.1)) { proxy.scrollTo(i) } }
            }
        }
        .foregroundStyle(.white)
        .background(RoundedRectangle(cornerRadius: 14, style: .continuous).fill(Color(white: 0.11).opacity(0.97)))
        .overlay(RoundedRectangle(cornerRadius: 14, style: .continuous).strokeBorder(.white.opacity(0.12)))
        .clipShape(RoundedRectangle(cornerRadius: 14, style: .continuous))
    }
}

struct PickerRow: View {
    let index: Int
    let item: ClipItem
    let selected: Bool

    var body: some View {
        HStack(spacing: 10) {
            Text(index < 10 ? "\((index + 1) % 10)" : " ")
                .font(.system(size: 11, weight: .bold, design: .rounded).monospacedDigit())
                .frame(width: 20, height: 20)
                .background(RoundedRectangle(cornerRadius: 5).fill(.white.opacity(selected ? 0.25 : 0.1)))
            Text(item.preview)
                .font(.system(size: 12.5))
                .lineLimit(1)
                .truncationMode(.tail)
                .frame(maxWidth: .infinity, alignment: .leading)
            Text(item.ago)
                .font(.system(size: 10.5))
                .foregroundStyle(.white.opacity(0.45))
        }
        .padding(.horizontal, 10)
        .frame(height: 40)
        .background(
            RoundedRectangle(cornerRadius: 9, style: .continuous)
                .fill(selected ? AnyShapeStyle(LinearGradient(colors: [Color(hex: 0x7C5CFF), Color(hex: 0xB04BF2)], startPoint: .leading, endPoint: .trailing))
                      : AnyShapeStyle(Color.clear))
        )
        .contentShape(Rectangle())
    }
}

// MARK: - Home section

struct ClipboardSection: View {
    @ObservedObject var history: ClipboardHistory
    @ObservedObject private var hotkeys = HotkeyStore.shared
    @AppStorage("clipboardHistory") private var enabled = true

    var body: some View {
        VStack(alignment: .leading, spacing: 12) {
            HStack(spacing: 10) {
                Text("Clipboard")
                    .font(.system(size: 17, weight: .semibold, design: .rounded))
                Text("\(history.items.count)/\(ClipboardHistory.limit)")
                    .font(.system(size: 12, weight: .semibold).monospacedDigit())
                    .padding(.horizontal, 7).padding(.vertical, 2)
                    .background(Capsule().fill(.primary.opacity(0.08)))
                Text("Press \(HotkeyStore.shared.label(.clipboard)) anywhere to paste from your history")
                    .font(.system(size: 12))
                    .foregroundStyle(.secondary)
                    .padding(.leading, 4)
                Spacer()
                HeaderButton(title: enabled ? "Pause" : "Resume", symbol: enabled ? "pause.circle" : "play.circle") { enabled.toggle() }
                HeaderButton(title: "Clear", symbol: "trash", destructive: true) { history.clear() }
                    .disabled(history.items.isEmpty)
            }
            if history.items.isEmpty {
                HStack(spacing: 10) {
                    Image(systemName: "doc.on.clipboard").foregroundStyle(.secondary)
                    Text(enabled ? "Copy text in any app and it will appear here — the last \(ClipboardHistory.limit) items are kept."
                                 : "Clipboard history is paused.")
                        .font(.system(size: 12.5)).foregroundStyle(.secondary)
                }
                .padding(14)
                .frame(maxWidth: .infinity, alignment: .leading)
                .background(RoundedRectangle(cornerRadius: 12, style: .continuous).fill(.primary.opacity(0.04)))
            } else {
                ScrollView(.horizontal, showsIndicators: false) {
                    HStack(spacing: 10) {
                        ForEach(Array(history.items.enumerated()), id: \.element.id) { i, item in
                            ClipCard(index: i, item: item)
                        }
                    }
                    .padding(.vertical, 4)
                    .padding(.horizontal, 2)
                }
            }
        }
    }
}

struct ClipCard: View {
    let index: Int
    let item: ClipItem
    @State private var hover = false

    var body: some View {
        VStack(alignment: .leading, spacing: 6) {
            HStack {
                Text("\(index + 1)")
                    .font(.system(size: 10.5, weight: .bold, design: .rounded))
                    .foregroundStyle(.white)
                    .frame(width: 18, height: 18)
                    .background(Circle().fill(LinearGradient(colors: [Color(hex: 0x7C5CFF), Color(hex: 0xC145F5)], startPoint: .topLeading, endPoint: .bottomTrailing)))
                Text(item.ago).font(.system(size: 10.5)).foregroundStyle(.tertiary)
                Spacer()
                if hover {
                    Button { ClipboardHistory.shared.remove(item) } label: {
                        Image(systemName: "xmark").font(.system(size: 9, weight: .bold)).foregroundStyle(.secondary)
                    }
                    .buttonStyle(.plain)
                    .help("Remove")
                }
            }
            Text(item.text.trimmingCharacters(in: .whitespacesAndNewlines))
                .font(.system(size: 12))
                .lineLimit(3)
                .frame(maxWidth: .infinity, maxHeight: .infinity, alignment: .topLeading)
        }
        .padding(10)
        .frame(width: 210, height: 92)
        .background(RoundedRectangle(cornerRadius: 12, style: .continuous).fill(.background.opacity(hover ? 1 : 0.8)))
        .overlay(RoundedRectangle(cornerRadius: 12, style: .continuous).strokeBorder(hover ? Color.accentColor.opacity(0.7) : .primary.opacity(0.07), lineWidth: hover ? 2 : 1))
        .contentShape(Rectangle())
        .onHover { h in withAnimation(.easeOut(duration: 0.12)) { hover = h } }
        .onTapGesture {
            ClipboardHistory.shared.copy(item)
            Toast.show("Copied — ready to paste", symbol: "doc.on.clipboard.fill")
        }
        .onDrag { NSItemProvider(object: item.text as NSString) }
        .help("Click to copy")
    }
}

// MARK: - Menu bar submenu

struct ClipboardMenu: View {
    @ObservedObject var history: ClipboardHistory
    var body: some View {
        Menu("Clipboard History") {
            Button("Open Picker…  \(HotkeyStore.shared.label(.clipboard))") { ClipboardPicker.show() }
            Divider()
            if history.items.isEmpty {
                Text("Nothing copied yet")
            } else {
                ForEach(history.items) { item in
                    Button(String(item.preview.prefix(60))) {
                        ClipboardHistory.shared.copy(item)
                        Toast.show("Copied — ready to paste", symbol: "doc.on.clipboard.fill")
                    }
                }
                Divider()
                Button("Clear History") { history.clear() }
            }
        }
    }
}
